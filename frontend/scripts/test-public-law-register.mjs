import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5186';
const output = process.env.TEST_OUTPUT || '../../browser-checks';
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  await context.addInitScript(() => localStorage.setItem('besma_local_test_notice_v1', '1'));
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  const privateRequests = [];
  page.on('request', r => { if (r.url().includes('api.besma.co.kr')) privateRequests.push(r.url()); });
  await page.goto(`${base}/law-register`);
  await page.getByText('28개 항목 · 10개 분류').waitFor();
  assert.equal(privateRequests.length, 0, 'public page must not call private API');
  await page.screenshot({ path: `${output}/law-desktop.png`, fullPage: true });
  await page.getByLabel('법령명·본문 키워드 검색').fill('누전차단기');
  assert.ok(await page.locator('details').count() > 0);
  await page.locator('.record-content button').first().click();
  await page.waitForFunction(() => document.querySelector('canvas')?.width > 0 && document.querySelector('.pdf-canvas-container')?.getAttribute('aria-busy') === 'false');
  assert.equal(await page.getByLabel('원문 페이지').inputValue(), '21');
  await page.screenshot({ path: `${output}/law-pdf-page21.png`, fullPage: true });
  await page.getByRole('button', { name: '다음', exact: true }).click();
  await page.waitForTimeout(300);
  assert.equal(await page.getByLabel('원문 페이지').inputValue(), '22');
  await page.getByRole('button', { name: '확대 +', exact: true }).click();
  await page.getByRole('button', { name: '회전 ↻', exact: true }).click();
  await page.waitForTimeout(400);
  await page.getByRole('tab', { name: '법 분류·내용 검색' }).click();
  await page.getByLabel('법령명·본문 키워드 검색').fill('없는검색어xyz123');
  await page.getByText('검색 결과가 없습니다.', { exact: false }).waitFor();
  await page.getByRole('button', { name: '전체 보기', exact: true }).click();
  await page.locator('select').selectOption('전기안전관리법');
  assert.equal(await page.locator('details').count(), 1);
  await page.goto(`${base}/login`);
  await page.getByRole('button', { name: '로그인', exact: true }).waitFor();
  await page.getByText('11월에 오픈합니다.').waitFor();
  await page.screenshot({ path: `${output}/login-desktop.png`, fullPage: true });
  for (const service of ['worker-voice', 'heat-stress', 'opinions']) {
    await page.goto(`${base}/services/${service}`);
    await page.waitForURL(`**/login?redirect=/services/${service}`);
    await page.getByRole('button', { name: '로그인', exact: true }).waitFor();
  }
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  await mobile.addInitScript(() => localStorage.setItem('besma_local_test_notice_v1', '1'));
  const mp = await mobile.newPage();
  mp.on('pageerror', e => errors.push(e.message));
  await mp.goto(`${base}/law-register`);
  await mp.getByText('28개 항목 · 10개 분류').waitFor();
  assert.equal(await mp.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile overflow');
  await mp.screenshot({ path: `${output}/law-mobile.png`, fullPage: true });
  await mp.getByRole('tab', { name: '서명본 원문' }).click();
  await mp.waitForFunction(() => document.querySelector('canvas')?.width > 0 && document.querySelector('.pdf-canvas-container')?.getAttribute('aria-busy') === 'false');
  await mp.screenshot({ path: `${output}/law-mobile-pdf.png`, fullPage: true });
  assert.equal(await mp.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile PDF overflow');
  await mp.goto(`${base}/login`);
  await mp.getByRole('button', { name: '로그인', exact: true }).waitFor();
  await mp.screenshot({ path: `${output}/login-mobile.png`, fullPage: true });
  assert.equal(await mp.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile login overflow');
  // A stale login must not prevent anonymous reading or trigger authentication requests.
  await context.addInitScript(() => localStorage.setItem('besma_token', 'expired-local-verification-token'));
  privateRequests.length = 0;
  await page.goto(`${base}/law-register`);
  await page.getByText('28개 항목 · 10개 분류').waitFor();
  assert.equal(privateRequests.length, 0);
  assert.deepEqual(errors, []);
  await fs.writeFile(`${output}/result.json`, JSON.stringify({ base, passed: true, privateRequests: 0, browserErrors: errors, checks: ['anonymous-search', 'category-filter', 'empty-search', 'PDF-page-link', 'PDF-navigation-zoom-rotation', 'mobile', 'login-menu', 'three-login-gates', 'stale-token-public-reading'] }, null, 2));
  console.log('PASS public law register desktop/mobile/PDF/login gates');
} finally { await browser.close(); }
